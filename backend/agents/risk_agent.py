from typing import Dict, Optional
from datetime import datetime
from pathlib import Path
import json
import re
from agents.document_agent import DocumentAgent
from agents.news_agent import NewsAgent
from agents.report_agent import ReportAgent
from services.groq_service import GroqService
from services.validation import cap_by_findings, clamp_score, normalize_level, require_list_of_dicts, unsupported_figures

# Titles of the three core statements, as US (10-K/10-Q) and Indian (Ind AS) reports write them.
# Matched case-sensitively, so list the usual capitalizations.
FINANCIAL_STATEMENT_TITLES = {
    "income": ["STATEMENTS OF OPERATIONS", "Statements of Operations", "STATEMENTS OF INCOME", "Statements of Income",
               "STATEMENT OF PROFIT AND LOSS", "Statement of Profit and Loss", "INCOME STATEMENT", "Income Statement"],
    "balance": ["BALANCE SHEETS", "Balance Sheets", "BALANCE SHEET", "Balance Sheet",
                "STATEMENT OF FINANCIAL POSITION", "Statement of Financial Position"],
    "cash_flow": ["STATEMENTS OF CASH FLOWS", "Statements of Cash Flows", "STATEMENT OF CASH FLOWS",
                  "Statement of Cash Flows", "CASH FLOW STATEMENT", "Cash Flow Statement"],
}

# Semantic searches for figures that appear outside the statements (press releases, MD&A, risk notes)
FINANCIAL_SEARCH_QUERIES = [
    "total revenue net sales operating income net income profit earnings per share year over year",
    "total debt borrowings term debt commercial paper total liabilities shareholders equity cash",
    "cash generated by operating activities free cash flow capital expenditure",
    "going concern impairment restatement material weakness default covenant significant decline loss",
]

MAX_CONTEXT_CHUNKS = 14  # ~14k characters of excerpts

# Weight of each 0-50 sub-score in the 0-100 overall score. The document is audited evidence;
# 30 days of headlines are context, so they count for less.
FINANCIAL_WEIGHT = 70
NEWS_WEIGHT = 30


class RiskAgent:
    """
    Phase 2 & 3 Agent — The Analyst
    Responsibilities:
      - Detect financial anomalies in documents
      - Cross-reference news signals with document data
      - Calculate the final ARIA Risk Score (0-100)
    """

    def __init__(self, doc_agent: DocumentAgent):
        self.doc_agent = doc_agent
        self.news_agent = NewsAgent()
        self.report_agent = ReportAgent()
        self.groq = GroqService()
        # Last analysis per document, so the PDF matches what the dashboard showed
        self.analyses_dir = Path("data/analyses")
        self.analyses_dir.mkdir(parents=True, exist_ok=True)

    def _analysis_path(self, doc_id: str) -> Optional[Path]:
        # doc_id comes from the URL — only accept real IDs (12 hex chars) so it can't escape the folder
        if not re.fullmatch(r"[0-9a-f]{12}", doc_id):
            return None
        return self.analyses_dir / f"{doc_id}.json"

    def load_analysis(self, doc_id: str) -> Optional[Dict]:
        path = self._analysis_path(doc_id)
        if path is None or not path.exists():
            return None
        return json.loads(path.read_text(encoding="utf-8"))

    def clear_analysis(self, doc_id: str):
        path = self._analysis_path(doc_id)
        if path is not None:
            path.unlink(missing_ok=True)

    def _statement_chunks(self, doc_id: str, titles: list[str]) -> list[str]:
        """
        Find a financial statement by its title and return it plus the following chunk
        (statements usually span a chunk boundary). Titles also appear in the table of
        contents, the auditor's report and the notes, so pick the match followed by the most
        figures — in the real statement the numbers start right after the title.
        """
        candidates = []
        for title in titles:
            for index, text in self.doc_agent.chroma.find_containing(doc_id, title).items():
                following = self.doc_agent.chroma.get_chunk(doc_id, index + 1) or ""
                after_title = (text[text.index(title):] + following)[:1500]
                density = sum(ch.isdigit() for ch in after_title) / max(len(after_title), 1)
                candidates.append((density, text, following))
        if not candidates:
            return []
        _, text, following = max(candidates, key=lambda c: c[0])
        return [text] + ([following] if following else [])

    def gather_financial_context(self, doc_id: str) -> list[str]:
        """Collect the parts of the document that matter for a financial health check."""
        chunks = []
        for titles in FINANCIAL_STATEMENT_TITLES.values():
            chunks += self._statement_chunks(doc_id, titles)
        for query in FINANCIAL_SEARCH_QUERIES:
            chunks += self.doc_agent.chroma.search(doc_id, query, n_results=3)
        # Keep order (statements first), drop duplicates, cap the prompt size
        return list(dict.fromkeys(chunks))[:MAX_CONTEXT_CHUNKS]

    def analyze_financial_anomalies(self, doc_id: str) -> Dict:
        """
        Ask the LLM to look for specific financial red flags in the document.
        """
        chunks = self.gather_financial_context(doc_id)
        if not chunks:
            raise ValueError("No searchable content found for this document. Try re-uploading it.")
        context = "\n\n---\n\n".join(chunks)

        prompt = f"""You are ARIA, a forensic financial auditor.
Using ONLY the document excerpts below, assess the company's financial health.

DOCUMENT EXCERPTS:
{context}

Rules:
- An anomaly is an ADVERSE change only: e.g. falling revenue or profit, shrinking margins, rising
  leverage, negative or falling operating cash flow, losses, impairments, going-concern or default warnings.
- Improvements are NOT anomalies: higher revenue or profit, lower debt, debt repayment, rising cash.
  For debt and liabilities a DECREASE is favorable. Negative investing cash flow (capital spending,
  buying securities) is normal for a healthy company, not an anomaly.
- Copy figures exactly as written in the excerpts (e.g. "$12,350M", not "$12.35B"); never invent numbers.
  If a metric isn't in the excerpts, leave it out.
- Report line items as stated. Don't add line items together to make your own totals (e.g. "total debt").
- For each anomaly set "direction" to "adverse" (got worse for the company) or "favorable".
- financial_risk_score (0-50):
    0-10  strong or improving financials
    11-20 stable with minor concerns
    21-35 material deterioration (e.g. revenue or profit down >10%, sharply rising leverage, negative cash flow)
    36-50 severe distress (large losses, liquidity crisis, default or going-concern warnings)

Output valid JSON only:
{{
  "key_metrics": [
    {{"metric": "Revenue", "current": "$416,161M (FY2025)", "prior": "$391,035M (FY2024)", "change": "+6.4%"}}
  ],
  "anomalies": [
    {{"metric": "Operating cash flow", "observation": "what got worse, with figures", "direction": "adverse", "severity": "high/medium/low"}}
  ],
  "financial_risk_score": 0,
  "summary": "1-2 sentence financial health summary citing the key figures"
}}
"""
        data = self.groq.ask_json(prompt)

        def grounded(item: dict, text: str) -> bool:
            # The model sometimes invents or adds up its own figures — keep only what the document states
            missing = unsupported_figures(text, context)
            if missing:
                print(f"[RiskAgent] Dropped {item.get('metric')!r}: figures not in document {missing}")
            return not missing

        key_metrics = [
            {k: str(m.get(k, "")) for k in ("metric", "current", "prior", "change")}
            for m in require_list_of_dicts(data, "key_metrics")
        ]
        anomalies = [
            {
                "metric": str(a.get("metric", "Unspecified")),
                "observation": str(a.get("observation", "")),
                "severity": normalize_level(a.get("severity")),
            }
            for a in require_list_of_dicts(data, "anomalies")
            # Improvements aren't risks, even when the model lists them
            if str(a.get("direction", "adverse")).strip().lower() != "favorable"
        ]
        anomalies = [a for a in anomalies if grounded(a, a["observation"])]
        score = cap_by_findings(clamp_score(data.get("financial_risk_score")), [a["severity"] for a in anomalies])
        return {
            "financial_risk_score": score,
            "key_metrics": [m for m in key_metrics if grounded(m, f"{m['current']} {m['prior']}")],
            "anomalies": anomalies,
            "summary": str(data.get("summary", "")),
        }

    def run_full_analysis(self, doc_id: str, progress_callback=None) -> Dict:
        """
        The main pipeline for Phase 2:
        1. Get document metadata (company name)
        2. Analyze financial anomalies via RAG
        3. Fetch and analyze live news
        4. Fuse data and calculate final score
        """
        if progress_callback: progress_callback(10, "Starting multi-source analysis...")
        # Get company name from metadata
        docs = self.doc_agent.list_documents()
        doc_info = next((d for d in docs if d["doc_id"] == doc_id), None)
        
        if not doc_info:
            return {"error": "Document not found"}

        company_name = doc_info.get("company", "Unknown Company")

        # 1. Financial Analysis
        if progress_callback: progress_callback(25, f"Analyzing financial health for {company_name}...")
        financial_analysis = self.analyze_financial_anomalies(doc_id)

        # 2. News Analysis
        if progress_callback: progress_callback(60, f"Searching live news for {company_name}...")
        # Give the news analyst the company's scale so it can judge how material each story is
        company_context = "\n".join(
            [financial_analysis["summary"]]
            + [f"{m['metric']}: {m['current']} (prior {m['prior']})" for m in financial_analysis["key_metrics"]]
        )
        news_analysis = self.news_agent.get_risk_report(company_name, company_context)

        # 3. Final Fusion & Scoring
        if progress_callback: progress_callback(85, "Fusing signals and calculating ARIA score...")
        # Each sub-score is 0-50; weight them into a 0-100 overall score
        f_points = round(financial_analysis["financial_risk_score"] / 50 * FINANCIAL_WEIGHT)
        n_points = round(news_analysis["news_risk_score"] / 50 * NEWS_WEIGHT)
        total_score = f_points + n_points

        # Determine overall rating
        rating = "Low Risk [STABLE]"
        if total_score > 70: rating = "Critical Risk [CRITICAL]"
        elif total_score > 40: rating = "Medium Risk [ELEVATED]"

        result = {
            "doc_id": doc_id,
            "company": company_name,
            "overall_risk_score": total_score,
            "rating": rating,
            "score_breakdown": {
                "financial": f_points, "financial_max": FINANCIAL_WEIGHT,
                "news": n_points, "news_max": NEWS_WEIGHT,
            },
            "financial_signals": financial_analysis,
            "news_signals": news_analysis,
            "timestamp": datetime.now().isoformat(),
        }
        path = self._analysis_path(doc_id)
        if path is not None:
            path.write_text(json.dumps(result, indent=2), encoding="utf-8")
        return result

    def generate_report(self, doc_id: str) -> str:
        """
        Generate a PDF report from the latest analysis (running one if none exists).
        Returns the path to the PDF.
        """
        analysis_data = self.load_analysis(doc_id) or self.run_full_analysis(doc_id)
        if "error" in analysis_data:
            raise ValueError(analysis_data["error"])
        
        pdf_path = self.report_agent.generate_pdf_report(analysis_data)
        return pdf_path
